def match_symptom_kb(question: str) -> list[dict]:
    """在问题中匹配症状关键词，返回命中的知识库条目（含来源信息）。"""
    if not question:
        return []
    lowered = question.lower()
    hits = []
    for key, entry in SYMPTOM_KB.items():
        if any(term in lowered for term in entry["terms"]):
            hits.append({**entry, "id": f"kb:{key}", "version": KB_VERSION})
    return hits


def symptom_kb_context(question: str) -> tuple[str, list[dict]]:
    """生成注入提示词的受控知识库上下文；未命中返回 (空串, [])。"""
    hits = match_symptom_kb(question)
    if not hits:
        return "", []
    lines = [f"健康知识库（{KB_VERSION}，人工整理的非诊断性科普，用于缓解担忧参考）："]
    for h in hits:
        benign = "、".join(h["benign"])
        red = "；".join(h["red_flags"])
        lines.append(f"- {h['id']}：常见良性可能：{benign}。就医信号：{red}。建议：{h['advice']}")
    return "\n".join(lines), hits
